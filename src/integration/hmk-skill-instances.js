/** The Appendix I realm tables frequently write dialect labels in a language
 * column. Appendix II pp.424–425 has ONE Language skill for their mother
 * tongue. Preserve the full printed dialect in the region evidence; this
 * canonical key is used ONLY by the Skill ledger and family boosts. */
export function canonicalLanguage(name){
 const raw=String(name??'').trim();
 const alias={'Triérzi':'Tríerzi','Eméla':'Emélan','Ánil Ketâri':'Anil Ketâri','Quârphic (varies)':'Quârphic'}[raw];
 if(alias)return alias;
 for(const root of ['Áltic','Tuvâran','Quârphic','Shôrka','Thónian','Nâsik Azéri'])
  if(raw.startsWith(root+'-')&&raw.length>root.length+1)return root;
 return raw;
}

