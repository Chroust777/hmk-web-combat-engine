/** HMK v1.2 pp.161,163–166. Character Sheet -> ONE real Combat action.
 * This module never generates dice, commits an event, or bypasses the guided
 * Attack / Defence / Injury / Mishap / Initiative engine. */
const validId = x => typeof x === 'string' && x.length > 0 && x.length <= 160;
const ACTIONS = Object.freeze(['melee','press','trip','grab','missile']);
const need = (ok,msg) => { if (!ok) throw Error(msg); };
export function prepareSheetCombatAction({actorId,targetId,kind,encounterIds,sequence,
 currentActorId,dueCount=0,guidedActive=false,signature}={}) {
 need(ACTIONS.includes(kind),'Neznámá pravidlová bojová akce');
 need(validId(actorId)&&validId(targetId)&&actorId!==targetId,'Chybí různí účastníci boje');
 need(Array.isArray(encounterIds)&&encounterIds.includes(actorId)&&encounterIds.includes(targetId),
  'Obě postavy musí být v potvrzeném střetnutí');
 need(sequence&&validId(sequence.timelineId)&&Number.isSafeInteger(sequence.round)&&sequence.round>0,
  'Přímá akce vyžaduje aktivní Initiative a doložené kolo');
 need(sequence.order?.includes(actorId)&&sequence.order.includes(targetId),
  'Aktér a cíl nejsou účastníky stejné Initiative');
 need(currentActorId===actorId,'Nejedná právě postava vybraná na Character Sheet');
 need(dueCount===0,'Nejprve vyřešte dřívější povinné Combat následky');
 need(!guidedActive,'Již probíhá pravidlový Combat průvodce');
 need(typeof signature==='string'&&signature.length>5,'Chybí podpis skutečného bojového kontextu');
 return Object.freeze({version:1,source:'character-sheet',actorId,targetId,kind,
  timelineId:sequence.timelineId,round:sequence.round,signature});
}
export function confirmSheetCombatAction(intent,{kind,actorId,targetId,sequence,signature}={}) {
 need(intent?.version===1&&intent.source==='character-sheet','Neexistuje doložený odkaz z Character Sheet');
 need(sequence?.round===intent.round&&sequence.timelineId===intent.timelineId,
  'Kolo nebo časová osa se od přípravy akce změnila');
 need(kind===intent.kind&&actorId===intent.actorId&&targetId===intent.targetId,
  'Bojová akce/aktér/cíl se od přípravy změnili; zvolte novou akci');
 need(signature===intent.signature,'Postavy, vybavení či Initiative se od přípravy akce změnily');
 return {version:1,source:'character-sheet',actorId,targetId,kind,
  timelineId:intent.timelineId,round:intent.round};
}
/** Validate that EVERY CF Mishap generated by a witnessed attack was resolved
 * once in the original follow-up; never infer a generic Skill Test consequence.
 * In a fatal Injury Sequence, a dead combatant may correctly skip a Mishap.
 */
export function combatMishapClosure({origin,gate,attackerId,defenderId,proofs=[],states={}}={}) {
 need(['melee','missile'].includes(origin)&&validId(attackerId)&&validId(defenderId)&&attackerId!==defenderId,
  'Chybí původní potvrzená bojová akce');
 need(gate&&Array.isArray(proofs),'Chybí výsledek útoku nebo důkazy Mishaps');
 const expected=origin==='melee'
  ? [{actorId:attackerId,kind:gate.attackerMishap},{actorId:defenderId,kind:gate.defenderMishap}].filter(x=>x.kind)
  : (Array.isArray(gate.forcedMishaps)&&gate.forcedMishaps.length
   ?gate.forcedMishaps.map(kind=>({actorId:attackerId,kind,forced:true}))
   :gate.mishap?[{actorId:attackerId,kind:gate.mishap}]:[]);
 need(expected.every(x=>['fumble','stumble'].includes(x.kind)),'Neznámý bojový Mishap');
 need(proofs.length===expected.length,'Počet vykonaných bojových Mishaps neodpovídá původnímu hodu');
 const seen=new Set(),records=[];
 for(let i=0;i<expected.length;i++) {
  const x=expected[i],p=proofs[i];
  need(p?.actorId===x.actorId,'Bojový Mishap je připsaný nesprávné postavě nebo v nesprávném pořadí');
  const dedup=p.eventId??x.actorId+':'+i;
  need(!seen.has(dedup),'Duplicitní ID stejného Mishap');seen.add(dedup);
  if(p.skipped){
   need(p.skipped==='killed-before-mishap'&&states[x.actorId]?.shock==='KIA',
    'Přeskočit lze jen Mishap postavy skutečně usmrcené během Injury Sequence');
   records.push({actorId:x.actorId,kind:x.kind,outcome:'skipped-kia',eventId:p.eventId??null});continue;
  }
  need(p.result&&typeof p.result.effect==='string'&&p.result.effect,
   'Mishap nebyl vyhodnocen původním Combat enginem');
  need(!p.kind||p.kind===x.kind||(x.kind==='fumble'&&p.kind==='stumble'),
   'Následek Fumble/Stumble nesouhlasí s původním bojovým CF');
  if(x.forced)need(p.forced===true,'Grievous: chybí důkaz automatického CF');
  records.push({actorId:x.actorId,kind:x.kind,appliedKind:p.kind??x.kind,outcome:p.result.effect,eventId:p.eventId??null,
   forced:p.forced===true});
 }
 return {version:1,origin,attackerId,defenderId,expectedCount:expected.length,
  resolvedCount:records.filter(x=>x.outcome!=='skipped-kia').length,records};
}
