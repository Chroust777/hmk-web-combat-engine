'use strict';
const assert=require('node:assert/strict');
(async()=>{
 const {missingPrintedArmourCatalogEntries}=await import('../src/integration/armour-article-catalog.js');
 const {PRINTED_ARMOUR_SUITS_P113_116}=await import('../src/rules/armour-suit-printed.js');
 const {previewOptimalOutfit,applyOptimalOutfit}=await import('../src/integration/hmk-outfit-optimizer.js');
 const {identifyWornPrintedSuit}=await import('../src/integration/printed-suit-combat.js');
 const {resolveCombatantLoad}=await import('../src/integration/combatant-load.js');
 const {auditArmourLoadout}=await import('../src/integration/armour-loadout-audit.js');
 const {layerDisplayRows,readableLayerIssues}=await import('../src/integration/hmk-armour-display.js');
 const {printedSuitAV}=await import('../src/rules/armour-all-suits-fixed.js');
 const catalog=missingPrintedArmourCatalogEntries([]);
 const normalize=name=>name.toLowerCase()==='great helm'?'plate great helm':name.toLowerCase();
 let count=0;
 const make=(name,options={})=>{
  const catalogItem=catalog.find(x=>x.name.toLowerCase()===normalize(name));
  assert.ok(catalogItem,'catalog: '+name);
  return {id:`owned-${++count}`,sourceItemId:catalogItem.id,characterId:options.owner||'P1',snapshot:structuredClone(catalogItem),quantity:1,condition:'',slot:options.slot||'carried',gearStowage:'normal',layerOrder:options.slot==='worn'?0:null,layerSlot:null,bulkExceptionZones:[],...(options.suit?{printedSuitName:options.suit,acquisition:{transactionId:options.receipt||'purchase-1',mode:'buy'}}:{})};
 };
 const owner={id:'P1',hmk:{attributes:{str:14}}};
 const b1=make('Cloth Breeches',{slot:'worn'}),b2=make('Cloth Breeches');
 const tunic=make('Cloth Tunic');const base=[b1,b2,tunic];
 const cv=previewOptimalOutfit(base,'P1','clothing');
 assert.equal(cv.ready,true,cv.reason);
 const worn1=applyOptimalOutfit(base,'P1',cv);
 assert.equal(worn1.filter(x=>x.slot==='worn'&&x.snapshot.name==='Cloth Breeches').length,1,'No duplicate breeches');
 assert.equal(base.filter(x=>x.slot==='worn').length,1,'No mutation of input');
 const doubleWorn=structuredClone(base);doubleWorn.find(x=>x.id===b2.id).slot='worn';doubleWorn.find(x=>x.id===b2.id).layerOrder=1;
 const fix=previewOptimalOutfit(doubleWorn,'P1','clothing');assert.equal(fix.ready,true,fix.reason);
 const one=applyOptimalOutfit(doubleWorn,'P1',fix);
 assert.equal(one.filter(x=>x.slot==='worn'&&x.snapshot.name==='Cloth Breeches').length,1,'Pre-existing two worn Breeches repaired');
 const suit=PRINTED_ARMOUR_SUITS_P113_116.find(x=>x.name==='Plate & Mail');
 const pieces=suit.articles.map(name=>make(name,{suit:suit.name}));
 assert.equal(pieces.length,17);
 const clothOut=[...worn1,...pieces];
 const result=previewOptimalOutfit(clothOut,'P1','armour');
 assert.equal(result.ready,true,result.reason);
 assert.equal(result.authoritativePreset,true);
 assert.equal(result.placements.length,17);
 assert.equal(result.unequipIds.length,worn1.filter(x=>x.slot==='worn').length);
 assert.equal(result.printedSuit,'Plate & Mail');
 const changed=applyOptimalOutfit(clothOut,'P1',result);
 assert.equal(changed.filter(x=>x.characterId==='P1'&&x.slot==='worn').length,17);
 assert.equal(changed.filter(x=>x.characterId==='P1'&&x.slot==='worn'&&x.snapshot.name==='Cloth Breeches').length,1);
 assert.equal(changed.filter(x=>x.id===b1.id)[0].slot,'carried');
 assert.equal(changed.filter(x=>x.id===b2.id)[0].slot,'carried');
 assert.equal(changed.filter(x=>x.slot==='worn').every(x=>x.layerOrder===null),true);
 const match=identifyWornPrintedSuit(changed,'P1');assert.equal(match.ok,true,match.reason);assert.equal(match.name,suit.name);
 const load=resolveCombatantLoad({character:owner,inventory:changed});
 assert.equal(load.printedSuit,suit.name);assert.equal(load.bulkReady,true,JSON.stringify(load.issues));
 assert.equal(load.armourENC,40,'Printed suit ENC used as reference');assert.equal(load.prohibitedOutfit,false);
 assert.equal(load.ready,true,JSON.stringify(load.issues));
 const rows=layerDisplayRows(auditArmourLoadout(changed.filter(x=>x.characterId==='P1')),changed.filter(x=>x.characterId==='P1'),load);
 assert.equal(rows.find(x=>x.location==='sk').protection.e,printedSuitAV('Plate & Mail','sk','e').av);
 assert.ok(rows.every(x=>x.status==='valid'));assert.deepEqual(readableLayerIssues(load,changed),[]);
 assert.equal(previewOptimalOutfit(changed,'P1','armour').ready,true);
 const second=applyOptimalOutfit(changed,'P1',previewOptimalOutfit(changed,'P1','armour'));
 assert.deepEqual(second,changed,'Idempotent equip');
 assert.throws(()=>applyOptimalOutfit(changed,'P1',result),/změnil/,'Stale confirmation cannot apply');
 const broken=pieces.filter((x,i)=>i!==0);
 assert.notEqual(previewOptimalOutfit([...worn1,...broken],'P1','armour').authoritativePreset,true,'Incomplete suit cannot claim printed preset');
 const different=[...pieces];different[0]={...different[0],sourceItemId:'fake'};
 assert.notEqual(previewOptimalOutfit([...worn1,...different],'P1','armour').authoritativePreset,true,'Fake article cannot pass suit proof');
 const other=make('Leather Vest',{owner:'P2'}),chest=make('Leather Vest',{slot:'chest'});
 const augmented=[...clothOut,other,chest];
 const q=previewOptimalOutfit(augmented,'P1','armour');assert.equal(q.ready,true);
 const mixed=applyOptimalOutfit(augmented,'P1',q);
 assert.equal(mixed.find(x=>x.id===other.id).slot,'carried');assert.equal(mixed.find(x=>x.id===chest.id).slot,'chest');
 console.log('PASS v93.521: duplicate Breeches prevented, Plate & Mail 17 equipped, published suit recovered, correct armour ENC, clothes replaced, 2nd equip idempotent, tamper/stale/chest/owner tests');
})().catch(e=>{console.error(e.stack);process.exit(1)});
