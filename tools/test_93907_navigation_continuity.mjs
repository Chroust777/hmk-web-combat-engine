import assert from 'node:assert/strict';
import {lastEpisodeBefore,lastNavigationEvidenceBefore,episodeNavigationState,EPISODE_NAVIGATION_EVIDENCE_POLICY_93907} from '../src/integration/hmk-time-episodes.js';
let n=0;
const eq=(a,b,m)=>{assert.deepEqual(a,b,m);n++};
const mk=(id,kind,actors,start,end,state,more={})=>({id,calendarCampaignId:'c',calendarTimeEpisode:{kind,memberIds:actors,startMinute:start,endMinute:end,...(state===undefined?{}:{navigationState:state}),...more}});
const a=[mk('lost','travel',['a'],0,30,'lost'),mk('rest-old','rest',['a'],30,270)];
eq(episodeNavigationState(lastEpisodeBefore(a,'c',270,['a'])),'clear','v93.906 reproduction: legacy rest resets Lost');
eq(lastNavigationEvidenceBefore(a,'c',270,['a']).id,'lost','new rule ignores unproven rest');
eq(episodeNavigationState(lastNavigationEvidenceBefore(a,'c',270,['a'])),'lost','new trail preserves Lost');
eq(EPISODE_NAVIGATION_EVIDENCE_POLICY_93907,'hmk-navigation-evidence-only-v93.907','policy id');
const noAuto=[...a,mk('rest-false-clear','rest',['a'],270,300,'clear')];
eq(lastNavigationEvidenceBefore(noAuto,'c',300,['a']).id,'lost','nontravel clear without decision is not proof');
const others=[...noAuto,mk('other-travel','travel',['b'],300,360,'clear')];
eq(lastNavigationEvidenceBefore(others,'c',370,['a']).id,'lost','other party clear cannot cancel A Lost');
eq(lastNavigationEvidenceBefore(others,'c',370,['b']).id,'other-travel','party B has own navigation');
const afterForage=[...others,mk('tracking','tracking',['a'],360,400),mk('forage','forage',['a'],400,500)];
eq(lastNavigationEvidenceBefore(afterForage,'c',501,['a']).id,'lost','foraging and tracking cannot reset Lost');
const recovered=[...afterForage,mk('bearing-restored','travel',['a'],501,530,'clear',{navigationRecovered:true})];
eq(episodeNavigationState(lastNavigationEvidenceBefore(recovered,'c',540,['a'])),'clear','confirmed special bearing restoration persists');
const mis=[mk('mis','travel',['a'],0,30,'misdirection'),mk('legacy-watch','watch',['a'],30,150)];
eq(episodeNavigationState(lastNavigationEvidenceBefore(mis,'c',151,['a'])),'misdirection','Misdirection persists after unauthenticated watch');
const observed=[...mis,mk('awareness-during-stationary','watch',['a'],150,270,'clear',{navigationRecovered:true})];
eq(episodeNavigationState(lastNavigationEvidenceBefore(observed,'c',271,['a'])),'clear','confirmed stationary recovery preserved');
eq(lastNavigationEvidenceBefore(observed,'c',150,['a']).id,'mis','future receipts excluded');
eq(lastNavigationEvidenceBefore([], 'c', 100, ['a']),null,'no invented navigation evidence');
console.log('PASS v93.907 legacy / modern navigation continuity',n,'assertions');
