import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
import {PRINTED_MISSILE_WEAPONS_P109_110} from '../src/rules/missile-weapons-printed-p109-110.js';
import {PRINTED_PROJECTILES_P108_110} from '../src/rules/projectiles-printed-p108-110.js';
import {annotatePrintedThrownWeapon} from '../src/integration/hmk-printed-thrown-weapon-modes.js';
import {libraryTabsForItem,libraryVisiblePage} from '../src/integration/hmk-library-tabs.js';
import {rangedCategories93805,filterRangedCatalogue93805} from '../src/integration/hmk-library-ranged-filters-93805.js';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const app=readFileSync(resolve(root,'app.js'),'utf8');
const library=readFileSync(resolve(root,'library.css'),'utf8');
const bow=PRINTED_MISSILE_WEAPONS_P109_110.find(x=>x.properties.missileType==='bow');
const crossbow=PRINTED_MISSILE_WEAPONS_P109_110.find(x=>x.properties.missileType==='crossbow');
const sling=PRINTED_MISSILE_WEAPONS_P109_110.find(x=>x.properties.missileType==='sling');
const arrow=PRINTED_PROJECTILES_P108_110.find(x=>x.properties.projectileKind==='arrow');
const javelin=annotatePrintedThrownWeapon({id:'throw:1',name:'Javelin',category:'weapon',properties:{heft:11,baseRangeFt:60,verifiedModes:[{name:'Thrust'}]}},'polearms:p102');
assert.deepEqual([bow,crossbow,sling,arrow].map(x=>rangedCategories93805(x)),Array.from({length:4},()=>['missile']));
assert.deepEqual(rangedCategories93805(javelin),['thrown']);
assert.deepEqual(libraryTabsForItem(javelin),['melee','ranged']);
const independent={id:'x',name:'Sword',category:'weapon',properties:{heft:7}};
assert.deepEqual(rangedCategories93805(independent),[]);
const data=[...PRINTED_MISSILE_WEAPONS_P109_110,...PRINTED_PROJECTILES_P108_110,javelin,independent];
const ranged=data.filter(x=>libraryTabsForItem(x).includes('ranged'));
const one=filterRangedCatalogue93805(data,'missile');
const two=filterRangedCatalogue93805(data,'thrown');
assert.equal(one.filter(x=>libraryTabsForItem(x).includes('ranged')).length,PRINTED_MISSILE_WEAPONS_P109_110.length+PRINTED_PROJECTILES_P108_110.length);
assert.deepEqual(two.filter(x=>libraryTabsForItem(x).includes('ranged')).map(x=>x.name),['Javelin']);
assert.equal(filterRangedCatalogue93805(data,'all').length,data.length);
assert.equal(libraryVisiblePage(two,'ranged').total,1);
assert.equal(libraryVisiblePage(two,'ranged','Javelin').total,1);
assert.equal(libraryVisiblePage(two,'ranged','Crossbow').total,0);
assert.equal(libraryVisiblePage(one,'ranged','Javelin').total,0);
assert.equal(libraryVisiblePage(one,'ranged','Crossbow').total,PRINTED_MISSILE_WEAPONS_P109_110.filter(x=>x.name.includes('Crossbow')).length+1);
assert.ok(app.includes('data-library-ranged-kind'));
assert.ok(app.includes('filterRangedCatalogue93805(catalogItems,libraryRangedKind)'));
assert.ok(app.includes('libraryPage=0;render();'));
assert.ok(library.includes('.library-ranged-filter-select'));
console.log(`PASS filter 93.805: ${ranged.length} total ranged records (${one.filter(x=>libraryTabsForItem(x).includes('ranged')).length} missile incl. ammo, 1 thrown), UI controls, pagination, search.`);
