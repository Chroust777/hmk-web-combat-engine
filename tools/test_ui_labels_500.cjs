'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
let passed=0;const check=(value,description)=>{assert.ok(value,description);passed++};
const inv=app.slice(app.indexOf('function characterInventoryOverview('),app.indexOf('\nfunction inventoryPartialDropForm('));
check(inv.includes('<th>Cena</th><th>Hmotnost</th><th>ENC zbroje</th>'),'inventory headings have no lb unit');
check(inv.includes('`${r.totalWeight.toFixed(1)} lb`'),'weight is displayed with lb at the value');
check(inv.includes('r.totalPrice!==null?`${r.totalPrice} d`'),'inventory price is the whole record price');
check(!inv.includes('Celkem ${r.totalPrice} d</span>'),'no secondary total price below item price');
check(!inv.includes('<th>Hmotnost (lb)</th>'),'inventory no longer shows lb in heading');
for(const label of ['Nesené / vybavené položky','Efektivní výbava pro Gear ENC','V Truhlici'])check(inv.includes(`'${label}'`),'mass summary label has no unit: '+label);
check(!inv.includes('Nesené / vybavené položky (lb)'),'mass summary heading not duplicated with lb');
const begin=app.indexOf('function libraryBrief('),end=app.indexOf('function libraryPrintedPages(',begin);
const fn=vm.runInNewContext(app.slice(begin,end)+'\n;libraryBrief',{esc:v=>String(v)});
const armour={category:'armor',properties:{material:'cloth',encumbrance:5,printedEncCode:'a',locationProtection:{tx:{b:1,e:1,p:1,f:1}},pricePence:40,weightLb:2}};
const armourOut=fn(armour);
check(armourOut[1]==='5 (podmíněné)','library armour ENC value has no repeated ENC');
check(armourOut[3]==='40 d'&&armourOut[4]==='2 lb','other catalogue values unaffected');
const noteStart=app.indexOf('function catalogNoteInCzech('),noteEnd=app.indexOf('\n const p=item.properties||{};',noteStart);
check(noteStart>0&&noteEnd>noteStart,'targeted Czech translation helper exists');
const translate=vm.runInNewContext(app.slice(noteStart,noteEnd)+'\n;catalogNoteInCzech');
check(translate('Poznámka k pokrytí','Location codes from p.118; layering, Bulk, ENC and armour totals not calculated.').startsWith('Kódy anatomických lokalit'),'printed coverage note translated');
check(translate('Poznámka k pokrytí','Anatomical dots from p.118; rigid coverage, ENC, layering and suit totals not calculated.').startsWith('Anatomické značky'),'second printed note translated');
check(translate('Poznámka k pokrytí','p118 verified anatomical coverage; legality of combined layers still requires audit').startsWith('Anatomické krytí'),'verified coverage note translated');
check(translate('Poznámky','Vlastní poznámka hráče')==='Vlastní poznámka hráče','custom records unchanged');
check(translate('Základní WQ','none')==='none','unrelated raw strings unchanged');
check(app.includes('catalogNoteInCzech(row[0],x)'),'translation is applied to scalar display');
check(app.includes('catalogNoteInCzech(niceKey(k),human(x))'),'translation is applied to nested scalar display');
check(app.includes("const APP_VERSION='93.500'"),'updated application version');
check(html.includes('v93.500')&&html.includes('hmk-app.bundle.js?v=93.500'),'updated index and bundle reference');
console.log('PASS '+passed+' display checks v93.500');
