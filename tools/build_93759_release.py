#!/usr/bin/env python3
"""Build/verify HMK Keeper's Ledger 93.759 FULL and delta PATCH from 93.758."""
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import zipfile

WORK = Path(__file__).resolve().parents[1]
MOUNT = Path('/mnt/data')
BASE = MOUNT/'HMK_Keeper_Ledger_v93.758_FULL.zip'
PATCH = MOUNT/'HMK_Keeper_Ledger_v93.759_PATCH.zip'
FULL = MOUNT/'HMK_Keeper_Ledger_v93.759_FULL.zip'
PREFIX = 'hmk-web-combat-engine-main/'


def sha(blob): return hashlib.sha256(blob).hexdigest()


def zip_bytes(zpath):
    with zipfile.ZipFile(zpath,'r') as z:
        assert z.testzip() is None, f'CRC failed: {zpath}'
        out = {}
        for n in z.namelist():
            if n.endswith('/'): continue
            assert n.startswith(PREFIX), f'Unexpected zip prefix {n}'
            assert n not in out, f'Duplicate zip entry {n}'
            rel = n[len(PREFIX):]
            assert rel and '..' not in Path(rel).parts and not rel.startswith('/'), f'Unsafe entry {n}'
            out[rel] = z.read(n)
        return out


def fs_bytes():
    found={}
    for path in WORK.rglob('*'):
        if not path.is_file(): continue
        rel=path.relative_to(WORK).as_posix()
        assert not path.is_symlink() and rel not in found
        found[rel]=path.read_bytes()
    return found


def write_zip(path, mapping):
    with zipfile.ZipFile(path,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=6,allowZip64=True) as z:
        for rel,data in sorted(mapping.items()):
            info=zipfile.ZipInfo(PREFIX+rel)
            info.date_time=(2026,11,6,18,15,0)
            info.compress_type=zipfile.ZIP_DEFLATED
            info.external_attr=0o644 << 16
            z.writestr(info,data,compress_type=zipfile.ZIP_DEFLATED,compresslevel=6)


def main():
    baseline=zip_bytes(BASE)
    active=fs_bytes()
    removed=set(baseline)-set(active)
    assert not removed, f'Removed baseline files: {removed}'
    modified=sorted(k for k in baseline if baseline[k]!=active[k])
    new=sorted(set(active)-set(baseline))
    # Manifest is generated by this script, and is intentionally not listed inside its own hash list.
    manifest={
        'product':'HMK Keeper\u2019s Ledger',
        'fromVersion':'93.758','toVersion':'93.759',
        'baselineZip':BASE.name,'baselineZipSha256':sha(BASE.read_bytes()),
        'archiveRoot':PREFIX,
        'baselineFileCount':len(baseline),
        'description':'Manifest own hash omitted by design to avoid recursive self-hash. The manifest is included in PATCH and FULL.',
        'files':[{'path':k,'status':('new' if k in new else 'modified'),'sha256':sha(active[k]),'bytes':len(active[k])} for k in sorted(modified+new)],
        'deletedFiles':[],
    }
    manifest_path=WORK/'docs/PATCH_MANIFEST_v93.759.json'
    manifest_path.write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    active=fs_bytes()
    removed=set(baseline)-set(active)
    changed={k:active[k] for k in active if k not in baseline or baseline[k]!=active[k]}
    assert not removed
    assert 'docs/PATCH_MANIFEST_v93.759.json' in changed
    assert b'93.759' in active['index.html'] and b'93.759' in active['app.js']
    assert active['docs/AUDIT_CESTOVANI_v93.759.md']==(MOUNT/'HMK_Keeper_Ledger_AUDIT_v93.759.md').read_bytes()
    write_zip(FULL,active)
    write_zip(PATCH,changed)
    verified_full=zip_bytes(FULL)
    verified_patch=zip_bytes(PATCH)
    assert verified_full == active, 'FULL contents not byte identical to staging dir'
    assert verified_patch == changed, 'PATCH contents not byte identical to changed files'
    assert set(verified_full)==set(baseline)|set(verified_patch)
    merged=dict(baseline); merged.update(verified_patch)
    assert merged==verified_full, 'Applying PATCH to 93.758 does not reproduce FULL'
    assert not (set(baseline)-set(verified_full))
    assert all(verified_full[k]==baseline[k] for k in baseline if k not in verified_patch)
    manifest_json=json.loads(verified_full['docs/PATCH_MANIFEST_v93.759.json'])
    assert set(x['path'] for x in manifest_json['files'])==set(changed)-{'docs/PATCH_MANIFEST_v93.759.json'}
    assert len([x for x in manifest_json['files'] if x['status']=='modified'])==len(modified)
    report={
      'base':BASE.name,'base_sha256':sha(BASE.read_bytes()),'base_files':len(baseline),
      'full':FULL.name,'full_sha256':sha(FULL.read_bytes()),'full_bytes':FULL.stat().st_size,'full_files':len(verified_full),
      'patch':PATCH.name,'patch_sha256':sha(PATCH.read_bytes()),'patch_bytes':PATCH.stat().st_size,'patch_files':len(verified_patch),
      'modified_files':len(modified),'new_files':len(new)+1,'deleted_files':len(removed),
      'crc_full':'PASS','crc_patch':'PASS','byte_diff_against_base':'PASS','apply_patch_equivalence':'PASS',
      'changed_production_files':[k for k in modified if not k.startswith('tools/') and not k.startswith('docs/')],
    }
    (MOUNT/'HMK_Keeper_Ledger_v93.759_INTEGRITY.json').write_text(json.dumps(report,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    print(json.dumps(report,ensure_ascii=False,indent=2))

if __name__ == '__main__': main()
