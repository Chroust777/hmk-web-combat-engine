const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
(async()=>{
let n=0;const ok=(v,msg)=>{assert.ok(v,msg);n++};
const {createNavigationHistory,uiRouteSignature}=await import('file://'+path.resolve(__dirname,'../src/integration/hmk-ui-navigation-history.js'));
const h=createNavigationHistory({limit:3});
ok(!h.canBack()&&!h.canForward(),'empty navigation history');
ok(h.visit({view:'characters'}),'initial route');
ok(!h.visit({view:'characters'}),'re-render cannot create spurious step');
h.rememberScroll(412);h.visit({view:'sheet',selected:'a'});h.visit({view:'calendar',section:'provisions'});
ok(h.length()===3,'three route visits');
ok(h.back().route.view==='sheet','first backward route');
ok(h.back().scrollY===412,'scroll position preserved');
ok(h.forward().route.selected==='a','forward returns original actor');
h.visit({view:'library',tab:'melee'});ok(!h.canForward(),'new navigation invalidates forward branch');
h.visit({view:'calendar',section:'travel'});ok(h.length()===3,'bounded stack');
ok(h.back().route.view==='library','prior view still present');
const item=h.current();item.route.view='FAKE';ok(h.current().route.view==='library','route snapshots cloned');
ok(uiRouteSignature({view:'a'})!==uiRouteSignature({view:'b'}),'stable route keys');
const app=fs.readFileSync(path.resolve(__dirname,'../app.js'),'utf8');
const calendar=fs.readFileSync(path.resolve(__dirname,'../src/integration/hmk-campaign-calendar-ui.js'),'utf8');
const css=fs.readFileSync(path.resolve(__dirname,'../styles.css'),'utf8');
ok(app.includes('data-ui-history="back"')&&app.includes('data-ui-history="forward"'),'global arrows next to left navigation');
ok(app.includes('if(!uiNavigationRestoring)uiNavigation.visit(nextRoute'),'render-based route tracking');
ok(app.includes('historyStep(button.dataset.uiHistory)'),'back and forward events');
ok(!app.includes('const overviewHTML=`${board}${partyProvisionCardsHTML(participants,true)}'),'no duplicate provisions on calendar overview');
ok(app.includes("activeCalendarSection==='provisions'?`${partyProvisionCardsHTML(participants)}"),'provisions tab retains personal evidence');
ok(!calendar.includes('Tuzyn Reckoning · kalendář</h2>'),'redundant heading removed');
ok(!calendar.includes('Tuzyn Reckoning · přiřazení skutečného data</h3>'),'redundant date assignment removed');
ok(!calendar.includes('Výchozí datum TR bylo GM potvrzeno'),'redundant TR confirmation removed');
ok(calendar.includes('hc-month-guide-list')&&calendar.includes('TR_MONTHS.map'),'month tooltip uses canonical names');
ok(app.includes('legacyOriginPanel=!clock.trOrigin'),'legacy origin action preserved only if needed');
ok(css.includes('.hmk-global-history{position:fixed'),'global controls fixed on scroll');
ok(css.includes('.hc-month-guide:hover>.hc-month-guide-list'),'hover reveals all months');
console.log('PASS',n,'global navigation and calendar presentation checks');
})().catch(e=>{console.error(e);process.exitCode=1});
