import assert from 'node:assert/strict';
import {initialCombatState,shockFollowupReadiness,applyConfirmedShockRecovery,validateCombatState} from '../src/integration/persistent-combat-state.js';
import {prepareGMShockStateChange} from '../src/integration/hmk-gm-shock-state-93826.js';
let n=0;
const set=(state,shock,minute=480)=>prepareGMShockStateChange({state,eventId:`gm-shock:${++n}__verified`,shock,reason:'GM potvrzuje skutečný doložený výchozí stav pacienta',minute,gmConfirmed:true}).state;
const pristine=initialCombatState();
let c=set(pristine,'UNC');
assert.equal(c.shock,'UNC');assert.equal(c.wounds.length,0);assert.equal(c.shockFollowup.domain,'gm-health');
assert.equal(c.shockFollowup.originMinute,480);
assert.equal(shockFollowupReadiness({state:c,round:2,characterId:'c',actorId:'c',elapsedMinutesSinceOriginal:9}).due,false);
assert.equal(shockFollowupReadiness({state:c,round:2,characterId:'c',actorId:'c',elapsedMinutesSinceOriginal:10}).due,true);
c=applyConfirmedShockRecovery({state:c,round:2,eventId:'test-shock-recovery-93826',sl:'S',timingConfirmed:true,characterId:'c',actorId:'c',elapsedMinutesSinceOriginal:10,shockML:60,roll:31}).state;
assert.equal(c.shock,'STN');assert.equal(c.shockFollowup.domain,'gm-health');assert.equal(c.shockFollowup.originMinute,490);
c=set(c,'KIA',490);assert.equal(c.shock,'KIA');assert.equal(c.shockFollowup,null);assert.equal(c.wounds.length,0);
c=set(c,'NONE',490);assert.equal(c.shock,'NONE');assert.equal(c.wounds.length,0);assert.equal(c.events.filter(x=>x.type==='gm-health-shock-set').length,3);
let unknown=set(initialCombatState(),'INC',null);
assert.equal(unknown.shockFollowup.originMinute,null);
validateCombatState(unknown);
unknown=set(unknown,'INC',525);assert.equal(unknown.shockFollowup.originMinute,525);assert.equal(unknown.wounds.length,0);
assert.throws(()=>set(initialCombatState(),'NONE'),/Cílový stav/);
assert.throws(()=>prepareGMShockStateChange({state:initialCombatState(),eventId:'gm-shock:invalid',shock:'UNC',reason:'Nepotvrzeno',minute:480,gmConfirmed:false}),/GM/);
console.log('PASS v93.826 GM shock transitions + recovery timing + no wound + no-calendar and reanchor + validation');
