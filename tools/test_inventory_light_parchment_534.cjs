'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const css=fs.readFileSync(path.join(root,'book-templates.css'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.match(html,/Keeper’s Ledger · v93\.534/);
assert.match(html,/book-templates\.css\?v=93\.534-/);
const final=css.slice(css.lastIndexOf('/* v93.534 —'));
assert.ok(final.length>1000,'v93.534 light-wash override present');
assert.match(final,/\.inv-ledger-table tbody tr > td,[\s\S]*\.inv-ledger-table tbody tr > th:first-child/);
assert.match(final,/\.inv-ledger-table thead tr > th,[\s\S]*\.inv-ledger-table thead tr > th:first-child/);
assert.equal((final.match(/url\('\.\/assets\/ui\/book\/clean_vellum\.png'\)/g)||[]).length,2,'existing parchment texture shared');
assert.ok((final.match(/rgba\(255,252,244,\.25\)/g)||[]).length>=4,'same light overlay for all cells');
assert.doesNotMatch(final,/vellum_master|position\s*:\s*static|position\s*:\s*relative|background-attachment\s*:\s*fixed/);
assert.match(css,/\.inv-ledger-table tbody th:first-child\{position:sticky!important/);
assert.match(css,/\.inv-table-scroll\.inv-15-rows\{max-height:650px!important/);
console.log('PASS inventory light parchment v93.534: shared texture/wash, sticky item column, scroll, release/cache');
