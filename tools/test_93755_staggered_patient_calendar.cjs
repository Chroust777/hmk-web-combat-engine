'use strict';
const assert=require('node:assert/strict');
(async()=>{
 const {initialCombatState}=await import('../src/integration/persistent-combat-state.js');
 const {createCampaignCalendar,anchorCampaignOrigin,campaignCalendarAgenda,advanceCampaignCalendar}=await import('../src/integration/hmk-campaign-calendar.js');
 const {applyConfirmedInjuryHealing}=await import('../src/integration/hmk-healing-persistence.js');
 const {mandatoryCalendarWindow}=await import('../src/integration/hmk-calendar-chronology.js');
 let count=0;const eq=(a,b,msg)=>{assert.deepEqual(a,b,msg);count++},ok=(v,msg)=>{assert.ok(v,msg);count++},bad=(f,rx)=>{assert.throws(f,rx);count++};
 const create=(id)=>{
  const state=initialCombatState();
  state.wounds.push({id:'w-'+id,location:'ua',severity:'S',level:2,aspect:'e',bleeding:false,nextAdvanceRound:null,
   healing:{treated:true,healingRate:4,nextHealingDay:5,infectionPossible:false}});
  return {id,name:id,kind:'PC',hmk:{attributes:{end:12,wil:12},healthState:state}};
 };
 const healthy={id:'healthy',name:'Zdravý průvodce',kind:'PC',hmk:{attributes:{end:12},healthState:initialCombatState()}},a=create('a'),b=create('b');
 const pendingBWound=b.hmk.healthState.wounds.pop();
 const group=[healthy,a,b];
 let clock=createCampaignCalendar({day:1,hour:8,minute:0,label:'Different anchored patients',eventId:'begin-755',gmConfirmed:true,campaignId:'c755',characterIds:group.map(x=>x.id)});
 clock=anchorCampaignOrigin(clock,{kind:'wound',characterId:'a',woundId:'w-a',eventId:'injury-a',gmConfirmed:true});
 eq(clock.minute,480,'Anchor must not advance time');
 clock=advanceCampaignCalendar(clock,{deltaMinutes:120,eventId:'healthy-alone-1',reason:'Only healthy actor travels while patient a stays',gmConfirmed:true,characters:group});
 eq(clock.minute,600,'Unselected injured patient does not force co-travel');
 b.hmk.healthState.wounds.push(pendingBWound);
 clock=anchorCampaignOrigin(clock,{kind:'wound',characterId:'b',woundId:'w-b',eventId:'injury-b',gmConfirmed:true});
 let agenda=campaignCalendarAgenda(clock,group,[]);
 let healing=agenda.future.filter(x=>x.kind==='healing').sort((x,y)=>x.minute-y.minute);
 eq(healing.map(x=>x.minute),[7680,7800],'Different absolute origins must yield two separate healing deadlines');
 eq(new Set(healing.map(x=>x.characterId)).size,2,'Each actor independently scheduled');
 const win=mandatoryCalendarWindow({minute:clock.minute,agenda,gmAgenda:[]});
 eq(win.maxAllowed,7080,'Healthy actor can advance up to nearest due test');
 bad(()=>advanceCampaignCalendar(clock,{deltaMinutes:7081,eventId:'illegal-skip-755',reason:'Forbidden deadline skip',gmConfirmed:true,characters:group}),/termín|splatn|přeskoč/i);
 clock=advanceCampaignCalendar(clock,{deltaMinutes:7080,eventId:'to-a',reason:'GM confirms activity of healthy actor only',gmConfirmed:true,characters:group});
 eq(clock.minute,7680);
 agenda=campaignCalendarAgenda(clock,group,[]);
 eq(agenda.due.filter(x=>x.kind==='healing').map(x=>x.characterId),['a'],'At a due, b not yet due');
 bad(()=>advanceCampaignCalendar(clock,{deltaMinutes:1,eventId:'illegal-cross',reason:'Skip overdue A',gmConfirmed:true,characters:group}),/termín/i);
 const original=JSON.stringify(a.hmk.healthState);
 const proofA=applyConfirmedInjuryHealing({state:a.hmk.healthState,round:1,eventId:'heal-a',woundId:'w-a',daySinceInjury:5,endurance:12,will:12,roll:20,gmConfirmed:true});
 eq(JSON.stringify(a.hmk.healthState),original,'No mutation before GM commit');
 a.hmk.healthState=proofA.state;
 agenda=campaignCalendarAgenda(clock,group,[]);
 ok(!agenda.due.some(x=>x.kind==='healing'&&x.characterId==='a'),'A discharged independently');
 eq(agenda.future.filter(x=>x.kind==='healing').map(x=>x.characterId),['b'],'B is still due later');
 clock=advanceCampaignCalendar(clock,{deltaMinutes:120,eventId:'to-b',reason:'GM confirms independent activity',gmConfirmed:true,characters:group});
 eq(clock.minute,7800);
 agenda=campaignCalendarAgenda(clock,group,[]);
 eq(agenda.due.filter(x=>x.kind==='healing').map(x=>x.characterId),['b'],'B reaches own due');
 const proofB=applyConfirmedInjuryHealing({state:b.hmk.healthState,round:1,eventId:'heal-b',woundId:'w-b',daySinceInjury:5,endurance:12,will:12,roll:20,gmConfirmed:true});
 b.hmk.healthState=proofB.state;
 agenda=campaignCalendarAgenda(clock,group,[]);
 ok(!agenda.due.some(x=>x.kind==='healing'),'Both procedures discharged');
 clock=advanceCampaignCalendar(clock,{deltaMinutes:60,eventId:'after-b-755',reason:'GM confirms another independent episode',gmConfirmed:true,characters:group});
 eq(clock.minute,7860);
 bad(()=>advanceCampaignCalendar(clock,{deltaMinutes:1,eventId:'after-b-755',reason:'No duplicated event',gmConfirmed:true,characters:group}),/ID/);
 console.log('PASS',count,'independent actor/one clock/two differently anchored healing terms/chronology/no duplicate');
})().catch(err=>{console.error('FAIL',err.stack||err);process.exitCode=1});
