'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
(async()=>{
const root=path.resolve(__dirname,'..');
const {missingPrintedArmourCatalogEntries}=await import('../src/integration/armour-article-catalog.js');
const {previewOptimalOutfit,applyOptimalOutfit,previewUndressOutfit,undressOutfit}=await import('../src/integration/hmk-outfit-optimizer.js');
const source=missingPrintedArmourCatalogEntries([]);
const pick=(material,name)=>{const s=source.find(x=>x.properties.material===material&&x.name.toLowerCase().endsWith(' '+name.toLowerCase()));assert.ok(s,material+' '+name);return s;};
let seq=0;
const make=(material,name,owner='P1',slot='carried')=>{const s=pick(material,name);return {id:`i${++seq}`,sourceItemId:s.id,characterId:owner,snapshot:structuredClone(s),slot,quantity:1,currentWQ:null,gearStowage:'normal',layerOrder:slot==='worn'?0:null,layerSlot:null,bulkExceptionZones:[],condition:''};};
const shoes=make('cloth','Cap'),mail=make('mail','Cowl'),shirt=make('cloth','Shirt'),leather=make('leather','Vest');
const weapon={id:'weapon123',characterId:'P1',slot:'main_hand',snapshot:{category:'weapon',name:'Shortsword'}};
const other=make('padded','Mittens','P2');
const chest=make('cloth','Breeches','P1','chest');
const original=[shoes,mail,shirt,leather,weapon,other,chest];
let p=previewOptimalOutfit(original,'P1','armour');assert.equal(p.ready,true,p.reason);assert.equal(p.optimal,true);
let out=applyOptimalOutfit(original,'P1',p);
assert.equal(original[0].slot,'carried','input must not mutate');
assert.equal(out.find(x=>x.id===weapon.id).slot,'main_hand');
assert.equal(out.find(x=>x.id===other.id).slot,'carried');
assert.equal(out.find(x=>x.id===chest.id).slot,'chest');
for(const x of out.filter(x=>x.characterId==='P1'&&x.slot==='worn'))assert.ok(x.layerOrder>=0);
assert.equal(new Set(out.map(x=>x.id)).size,out.length);
assert.equal(previewOptimalOutfit(out,'P1','armour').ready,true);
const pc=previewOptimalOutfit(out,'P1','clothing');assert.equal(pc.ready,true,pc.reason);
const clothOut=applyOptimalOutfit(out,'P1',pc);
assert.ok(clothOut.filter(x=>x.slot==='worn'&&x.characterId==='P1').every(x=>x.snapshot.properties.material==='cloth'));
assert.equal(clothOut.find(x=>x.id===mail.id).slot,'carried');
assert.ok(previewUndressOutfit(clothOut,'P1').length>0);
const nude=undressOutfit(clothOut,'P1');
assert.equal(nude.filter(x=>x.slot==='worn'&&x.characterId==='P1').length,0);
assert.equal(nude.find(x=>x.id===weapon.id).slot,'main_hand');
assert.equal(nude.find(x=>x.id===other.id).slot,'carried');
assert.deepEqual(out.map(x=>x.id),original.map(x=>x.id),'no parallel inventory');
assert.throws(()=>applyOptimalOutfit([...original,{...make('cloth','Tunic')}],'P1',p),/změnil/);
const stale=structuredClone(p);stale.totalAV+=10;
assert.throws(()=>applyOptimalOutfit(original,'P1',stale),/změnil/);
const fake=structuredClone(mail);fake.snapshot.properties.locationProtection.sk.b=99;
assert.match(previewOptimalOutfit([fake],'P1').reason,/differs|Neověřené/i);
const qty=structuredClone(shoes);qty.quantity=2;
assert.match(previewOptimalOutfit([qty],'P1').reason,/více kusů/);
const unknown=structuredClone(shoes);unknown.sourceItemId='fake-id';
assert.equal(previewOptimalOutfit([unknown],'P1').ready,false);
const noSuitable=previewOptimalOutfit([weapon],'P1');assert.equal(noSuitable.ready,false);
// Conflict search must finish and prove an optimum, not silently choose greedily.
const conflict=[make('cloth','Cap'),make('padded','Cap'),make('quilted','Cap')];
const contested=previewOptimalOutfit(conflict,'P1','armour');
assert.equal(contested.ready,true,contested.reason);
assert.match(contested.proof,/Úplný průchod/);
assert.ok(contested.placements.length<=3);
assert.equal(applyOptimalOutfit(conflict,'P1',contested).filter(x=>x.slot==='worn').length,contested.placements.length);
const src=fs.readFileSync(path.join(root,'app.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.match(src,/APP_VERSION='93\.520'/);assert.match(html,/v93\.520/);
for(const action of ['armour','clothing','undress'])assert.ok(src.includes('data-outfit-action="'+action+'"'));
assert.match(src,/if\(combatInitiativeSequence\)return alert\('Během Initiative/);
assert.match(src,/hideVisibleTechnicalUUIDs\(app\)/);
console.log('PASS v93.520 outfit: verified source, full/cloth/dress/undress, CAS proof, owner/hand/chest unchanged, stale/tampered/quantity rejection');
})().catch(e=>{console.error(e);process.exitCode=1});
