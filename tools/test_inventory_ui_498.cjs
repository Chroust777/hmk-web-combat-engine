'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');let passed=0;
function check(test,description){assert.ok(test,description);passed++}
(async()=>{
 const s=fs.readFileSync(path.join(root,'app.js'),'utf8');
 const projectSrc=fs.readFileSync(path.join(root,'src/integration/hmk-inventory-overview.js'),'utf8');
 const {projectInventoryRows,inventoryTotals}=await import('data:text/javascript;base64,'+Buffer.from(projectSrc).toString('base64'));
 const rec=(id,wq,quantity=1)=>({id,characterId:'pc',sourceItemId:'test:dagger',quantity,slot:'carried',currentWQ:wq,condition:'',snapshot:{id:'test:dagger',name:'Dagger',category:'weapon',properties:{pricePence:10,weightLb:1,quality:12}}});
 const inventory=[rec('one',12),rec('two',12),rec('damaged',7)];
 const before=JSON.stringify(inventory),rows=projectInventoryRows(inventory);
 check(rows.length===3,'one source row per inventory record, even for same name and WQ');
 check(rows[0].item.id==='one'&&rows[1].item.id==='two','source identities not conflated');
 check(rows[2].wq===7,'damaged WQ stays distinct');
 check(inventoryTotals(rows).knownWeightLb===3,'weight is original sum');
 check(inventoryTotals(rows).knownValue===30,'price is original sum');
 check(JSON.stringify(inventory)===before,'projection does not modify source inventory');
 check(s.includes('const rows=sourceRows,totals=inventoryTotals(sourceRows);'),'inventory overview does not stack');
 check(!s.includes('const rows=groupInventoryDisplayRows(sourceRows)'),'former stacking removed from view');
 const overview=s.slice(s.indexOf('function characterInventoryOverview('),s.indexOf('\nfunction inventoryPartialDropForm('));
 check(!overview.includes('<th>Ks</th>'),'quantity column removed');
 check(overview.includes('data-inv-item-id="${esc(x.id)}"'),'per-row action points to original record');
 check(!overview.includes('data-inv-member-select'),'former group-level selection removed');
 check(overview.includes('waterContainerCapacity(x)'),'water state limited to verified vessels');
 check(overview.includes("waterAmount<=0?' (prázdná)'"),'empty vessel label');
 check(overview.includes("waterAmount>=vesselCapacity?' (plná vody)'"),'full vessel label');
 check(overview.includes('částečně naplněná'),'partially-filled jug not mislabelled');
 check(overview.includes('currentWater.some('),'partial water action backed by water receipt');
 check(overview.includes('kusů v původním záznamu'),'legacy multiple-quantity records not misrepresented');
 const form=s.slice(s.indexOf('function journalAddInventoryForm('),s.indexOf('\nfunction sheetSupplementTabs('));
 check(form.includes("numericField('currentWQ'"),'manual optional WQ input exists');
 check(form.includes('prázdné = katalog'),'optional WQ fallback explained');
 check(s.includes("const currentWQ=givenWQ!==''?requestedWQ:"),'manual WQ takes precedence');
 check(s.includes("givenWQ===''?null:Number(givenWQ)"),'empty input distinct from zero');
 check(s.includes("!/^(?:0|[1-9]\\d*)$/.test(givenWQ)"),'reject malformed numeric input');
 check(s.includes("if(element.hasAttribute('title'))element.removeAttribute('title')"),'custom tooltip strips duplicate native title');
 const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
 check(html.includes('v93.498')&&html.includes('hmk-app.bundle.js?v=93.498'),'HTML release and cache name updated');
 check(s.includes("const APP_VERSION='93.498'"),'app version updated');
 console.log(`PASS ${passed} checks – individual inventory rows, water state, optional WQ and one tooltip`);
})().catch(e=>{console.error(e);process.exitCode=1});
