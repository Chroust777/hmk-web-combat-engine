'use strict';
const assert=require('node:assert/strict');
(async()=>{
 const {skillWorkbenchHTML}=await import('../src/integration/hmk-skill-workbench-ui.js');
 const {SKILL_DEFINITIONS}=await import('../src/integration/hmk-character-creation.js');
 const {resolveOpposedTests}=await import('../src/integration/hmk-skill-test-engine.js');
 const skills=SKILL_DEFINITIONS.map((s,i)=>({name:s.name,ml:40+i%20}));
 const actor={id:'a',name:'A',hmk:{skills,attributes:{str:12,agl:12,wil:12,elo:11}}};
 const defender={id:'b',name:'B',hmk:{skills,attributes:{str:13,agl:10,wil:14,elo:12}}};
 let html=skillWorkbenchHTML(actor,[actor,defender],[],[],'secondary');
 let checks=0,ok=(v,m)=>{assert.ok(v,m);checks++};
 for(const s of SKILL_DEFINITIONS)ok(html.includes('value="'+s.name+'"'),'display skill in Primary/Defender selects: '+s.name);
 ok(html.includes('data-opposed-rule-guidance'),'scope of all counter skill selections explained');
 ok(html.includes('name="opposedAction"'),'official opposed action selector exists');
 ok(html.includes('name="opponentSkill"'),'defender mastery selector exists');
 ok(html.includes('name="rollA"')&&html.includes('name="rollB"'),'two independent original d100 fields');
 const failedA={sl:1,level:'F',roll:71,ml:70};const failedB={sl:1,level:'F',roll:72,ml:70};
 const persuasion=resolveOpposedTests(failedA,failedB,{persuasion:true});
 const saved={id:'test-a',characterId:'a',title:'Opposed · Charm',createdAt:'2026-10-27T12:01:00Z',skillTestProof:{type:'opposed-success-test',actorId:'a',opponentId:'b',skills:['Charm','Will'],a:failedA,b:failedB,comparison:persuasion}};
 html=skillWorkbenchHTML(actor,[actor,defender],[],[saved],'secondary');
 ok(html.includes('skill-tiebreak-form'),'mandatory tiebreak form visible for persuasion F/F');
 ok(html.includes('Povinný rozstřel Persuasion'),'clear p138 tie exception for GM');
 ok(html.includes('Rozhodnutí proběhne podle vyššího')&&!html.includes('name="tieD10A"'),'highest original d100 decides without new dice');
 const same={...saved,skillTestProof:{...saved.skillTestProof,a:{...failedA,roll:75,ml:60},b:{...failedB,roll:75,ml:60},comparison:resolveOpposedTests({...failedA,roll:75,ml:60},{...failedB,roll:75,ml:60},{persuasion:true})}};
 html=skillWorkbenchHTML(actor,[actor,defender],[],[same],'secondary');
 ok(html.includes('name="tieD10A"')&&html.includes('name="tieD10B"'),'mandatory d10 inputs for same d100 and ML');
 const normal={...saved,skillTestProof:{...saved.skillTestProof,skills:['Fishing','Endurance'],comparison:resolveOpposedTests(failedA,failedB)}};
 html=skillWorkbenchHTML(actor,[actor,defender],[],[normal],'secondary');
 ok(!html.includes('skill-tiebreak-form'),'ordinary failed opposed has no tiebreak');
 console.log('PASS v93.535 Skill Workbench ·',checks,'checks including 69 base masteries, opposed setup and persuasion ties');
})().catch(e=>{console.error(e.stack||e);process.exit(1)});
