assert.ok(source.startsWith('function trekResolveActorToken'));
const data={characters:[{id:'uuid-1',name:'Průvodce'},{id:'uuid-2',name:'Mezek Blesk'},{id:'uuid-3',name:'Petr'}]};
const resolve=new Function('data',`${source}\nreturn trekResolveActorToken;`)(data);
assert.equal(resolve('mezek blesk',{unregisteredAllowed:true}),'uuid-2');
assert.equal(resolve('PETR'),'uuid-3');
assert.equal(resolve('uuid-2'),'uuid-2');
assert.equal(resolve('Cizí soumar',{unregisteredAllowed:true}),'Cizí soumar');
assert.throws(()=>resolve('Neznámý honák'),/nebyl nalezen/);
data.characters.push({id:'uuid-4',name:'Mezek Blesk'});
assert.throws(()=>resolve('mezek blesk',{unregisteredAllowed:true}),/více postavám/);
assert.match(app,/function hideVisibleTechnicalUUIDs\(root\)/);
assert.match(app,/hideVisibleTechnicalUUIDs\(app\);/);
console.log(`PASS v93.519 Trekking UI: ${expected.length} field types, 7 sections, 8 steps, Czech help, ID-safe names, duplicate-name rejection, version and bundle`);
