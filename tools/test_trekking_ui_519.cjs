assert.equal(actual.length,expected.length,'Dynamic participant checkboxes expand at runtime');
const tooltipBlock=app.split('const TREKKING_FIELD_HELP=Object.freeze({')[1]?.split('});')[0];
assert.ok(tooltipBlock);
for(const key of expected)assert.match(tooltipBlock,new RegExp('\\b'+key+':'),`Missing Czech help: ${key}`);
for(const forbidden of ['<span>${esc(c.name)} · ${esc(c.id)}</span>','return `${esc(c.id)} (${esc(c.name||c.id)}'])assert.ok(!fragment.includes(forbidden),'Technical IDs visible in travel UI');
