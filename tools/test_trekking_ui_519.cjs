'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const css=fs.readFileSync(path.join(root,'book-templates.css'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const bundle=fs.readFileSync(path.join(root,'hmk-app.bundle.js'),'utf8');
assert.match(app,/APP_VERSION='93\.519'/);
assert.match(html,/Keeper’s Ledger · v93\.519/);
assert.ok(bundle.includes("APP_VERSION = '93.519'"));
assert.match(css,/\.hc-trek-routine\{container-type:inline-size\}/);
const fragment=app.split(' const trekPanel=`')[1]?.split(' const repairAssessments=')[0];
assert.ok(fragment,'Trekking HTML was not found');
for(let i=1;i<=7;i++)assert.ok(fragment.includes(`<legend>${i} · `),'Missing section '+i);
assert.match(fragment,/Jak postupovat při cestování – krok za krokem/);
